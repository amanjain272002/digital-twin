# ============================================================
# SESSION VALIDATION
# ============================================================

def validate_session_id(
    session_id: str
) -> str:

    if not session_id:
        raise HTTPException(
            status_code=400,
            detail="Session ID cannot be empty."
        )

    # UUIDs are generated by this application.
    # Only allow safe UUID-like values.
    if not re.fullmatch(
        r"[a-fA-F0-9-]{20,100}",
        session_id
    ):
        raise HTTPException(
            status_code=400,
            detail="Invalid session ID."
        )

    return session_id


# ============================================================
# MEMORY
# ============================================================

def get_memory_path(
    session_id: str
) -> str:

    validate_session_id(session_id)

    return f"{session_id}.json"


def load_conversation(
    session_id: str
) -> List[Dict[str, Any]]:
    """
    Load conversation history from S3 or local storage.
    """

    session_id = validate_session_id(
        session_id
    )

    # ========================================================
    # S3
    # ========================================================

    if USE_S3:

        if not S3_BUCKET:

            raise RuntimeError(
                "USE_S3=true but S3_BUCKET is not configured."
            )

        try:

            response = s3_client.get_object(
                Bucket=S3_BUCKET,
                Key=get_memory_path(session_id)
            )

            body = response["Body"].read().decode(
                "utf-8"
            )

            data = json.loads(body)

            if not isinstance(data, list):
                return []

            return data

        except ClientError as e:

            error_code = (
                e.response
                .get("Error", {})
                .get("Code", "")
            )

            if error_code in [
                "NoSuchKey",
                "404"
            ]:

                return []

            if error_code == "NoSuchBucket":

                raise RuntimeError(
                    f"S3 bucket does not exist: {S3_BUCKET}"
                )

            print(
                f"S3 load error: {error_code}: {e}"
            )

            raise

    # ========================================================
    # LOCAL
    # ========================================================

    os.makedirs(
        MEMORY_DIR,
        exist_ok=True
    )

    file_path = os.path.join(
        MEMORY_DIR,
        get_memory_path(session_id)
    )

    if not os.path.exists(file_path):
        return []

    try:

        with open(
            file_path,
            "r",
            encoding="utf-8"
        ) as f:

            data = json.load(f)

            if not isinstance(data, list):
                return []

            return data

    except json.JSONDecodeError:

        print(
            f"Invalid conversation file: {file_path}"
        )

        return []


def save_conversation(
    session_id: str,
    messages: List[Dict[str, Any]]
):
    """
    Save conversation history to S3 or local storage.
    """

    session_id = validate_session_id(
        session_id
    )

    # ========================================================
    # S3
    # ========================================================

    if USE_S3:

        if not S3_BUCKET:

            raise RuntimeError(
                "USE_S3=true but S3_BUCKET is not configured."
            )

        s3_client.put_object(

            Bucket=S3_BUCKET,

            Key=get_memory_path(session_id),

            Body=json.dumps(
                messages,
                indent=2,
                ensure_ascii=False
            ).encode("utf-8"),

            ContentType="application/json"
        )

        return

    # ========================================================
    # LOCAL
    # ========================================================

    os.makedirs(
        MEMORY_DIR,
        exist_ok=True
    )

    file_path = os.path.join(
        MEMORY_DIR,
        get_memory_path(session_id)
    )

    with open(
        file_path,
        "w",
        encoding="utf-8"
    ) as f:

        json.dump(
            messages,
            f,
            indent=2,
            ensure_ascii=False
        )


# ============================================================
# BEDROCK
# ============================================================

def call_bedrock(
    conversation: List[Dict[str, Any]],
    user_message: str
) -> str:

    if not user_message or not user_message.strip():

        raise HTTPException(
            status_code=400,
            detail="Message cannot be empty."
        )

    # ========================================================
    # SYSTEM PROMPT
    # ========================================================

    try:

        from context import prompt

        system_prompt = prompt()

    except Exception as e:

        print(
            f"Could not load context.prompt(): {e}"
        )

        system_prompt = (
            "You are an AI digital twin assistant. "
            "Answer clearly, accurately, and helpfully."
        )

    # ========================================================
    # BEDROCK HISTORY
    # ========================================================

    messages = []

    # Keep the most recent 50 messages.
    for msg in conversation[-50:]:

        role = msg.get("role")

        content = msg.get("content")

        if role not in [
            "user",
            "assistant"
        ]:
            continue

        if not content:
            continue

        messages.append(
            {
                "role": role,

                "content": [
                    {
                        "text": str(content)
                    }
                ]
            }
        )

    # ========================================================
    # CURRENT USER MESSAGE
    # ========================================================

    messages.append(
        {
            "role": "user",

            "content": [
                {
                    "text": user_message.strip()
                }
            ]
        }
    )

    # ========================================================
    # DEBUG
    # ========================================================

    print("")
    print("========================================")
    print("BEDROCK REQUEST")
    print("========================================")
    print(f"Model ID      : {BEDROCK_MODEL_ID}")
    print(f"AWS Region    : {AWS_REGION}")
    print(f"Messages      : {len(messages)}")
    print("API           : Converse")
    print("========================================")
    print("")

    try:

        # ====================================================
        # CONVERSE
        # ====================================================

        response = bedrock_client.converse(

            modelId=BEDROCK_MODEL_ID,

            system=[
                {
                    "text": system_prompt
                }
            ],

            messages=messages,

            inferenceConfig={
                "maxTokens": 2000,
                "temperature": 0.7,
                "topP": 0.9
            }
        )

        # ====================================================
        # EXTRACT RESPONSE
        # ====================================================

        output = response.get(
            "output",
            {}
        )

        assistant_message = output.get(
            "message",
            {}
        )

        content = assistant_message.get(
            "content",
            []
        )

        text_parts = []

        for item in content:

            if "text" in item:

                text_parts.append(
                    item["text"]
                )

        assistant_response = "".join(
            text_parts
        ).strip()

        if not assistant_response:

            raise RuntimeError(
                "Bedrock returned an empty text response."
            )

        print(
            "Bedrock response received successfully."
        )

        return assistant_response

    except ClientError as e:

        error = e.response.get(
            "Error",
            {}
        )

        error_code = error.get(
            "Code",
            "Unknown"
        )

        error_message = error.get(
            "Message",
            str(e)
        )

        request_id = (
            e.response
            .get("ResponseMetadata", {})
            .get("RequestId")
        )

        print("")
        print("========================================")
        print("BEDROCK ERROR")
        print("========================================")
        print(f"Error Code    : {error_code}")
        print(f"Error Message : {error_message}")
        print(f"Request ID    : {request_id}")
        print(f"Model ID      : {BEDROCK_MODEL_ID}")
        print(f"AWS Region    : {AWS_REGION}")
        print("========================================")
        print("")

        if error_code == "ValidationException":

            raise HTTPException(
                status_code=400,
                detail=(
                    "Bedrock ValidationException: "
                    f"{error_message}"
                )
            )

        if error_code == "AccessDeniedException":

            raise HTTPException(
                status_code=403,
                detail=(
                    "Bedrock AccessDeniedException: "
                    f"{error_message}"
                )
            )

        if error_code == "ResourceNotFoundException":

            raise HTTPException(
                status_code=404,
                detail=(
                    "Bedrock ResourceNotFoundException: "
                    f"{error_message}"
                )
            )

        if error_code == "ThrottlingException":

            raise HTTPException(
                status_code=429,
                detail=(
                    "Bedrock ThrottlingException: "
                    f"{error_message}"
                )
            )

        raise HTTPException(
            status_code=500,
            detail=(
                f"Bedrock error ({error_code}): "
                f"{error_message}"
            )
        )

    except HTTPException:

        raise

    except Exception as e:

        print("")
        print("========================================")
        print("UNEXPECTED BEDROCK ERROR")
        print("========================================")
        print(str(e))
        print("========================================")
        print("")

        raise HTTPException(
            status_code=500,
            detail=f"Bedrock request failed: {str(e)}"
        )


