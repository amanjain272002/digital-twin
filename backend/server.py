@app.post(
    "/chat",
    response_model=ChatResponse
)
async def chat(
    request: ChatRequest
):

    # ========================================================
    # VALIDATE
    # ========================================================

    message = request.message.strip()

    if not message:

        raise HTTPException(
            status_code=400,
            detail="Message cannot be empty."
        )

    # ========================================================
    # SESSION
    # ========================================================

    if request.session_id:

        session_id = validate_session_id(
            request.session_id
        )

    else:

        session_id = str(
            uuid.uuid4()
        )

    print("")
    print("========================================")
    print("CHAT REQUEST")
    print("========================================")
    print(f"Session ID : {session_id}")
    print(f"Message    : {message}")
    print("========================================")
    print("")

    # ========================================================
    # LOAD MEMORY
    # ========================================================

    conversation = load_conversation(
        session_id
    )

    # ========================================================
    # CALL BEDROCK
    # ========================================================

    assistant_response = call_bedrock(
        conversation,
        message
    )

    # ========================================================
    # SAVE MEMORY
    # ========================================================

    timestamp = datetime.now(
        timezone.utc
    ).isoformat()

    conversation.append(
        {
            "role": "user",
            "content": message,
            "timestamp": timestamp
        }
    )

    conversation.append(
        {
            "role": "assistant",
            "content": assistant_response,
            "timestamp": datetime.now(
                timezone.utc
            ).isoformat()
        }
    )

    save_conversation(
        session_id,
        conversation
    )

    # ========================================================
    # RESPONSE
    # ========================================================

    return ChatResponse(
        response=assistant_response,
        session_id=session_id
    )


